"""Reproduce vendored display fonts. Requires fonttools==4.65.0 brotli==1.2.0.
Sources are pinned; --cache defaults to .local/font-sources. Never used by the Worker.
"""
import argparse
import hashlib
import json
import re
import urllib.request
from pathlib import Path
import brotli
import fontTools
from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[1]
EXCAL = '7ded689cad49331167e29fd88b38f38d3736d576'
GOOGLE = 'bbda7253fc363238b05d97515ca71f8ae49c4fa9'
assert fontTools.__version__ == '4.65.0' and brotli.__version__ == '1.2.0'
args = argparse.ArgumentParser()
args.add_argument('--cache', type=Path, default=ROOT / '.local/font-sources')
cache = args.parse_args().cache
cache.mkdir(parents=True, exist_ok=True)
manifest_path = ROOT / 'docs/fonts/manifest.json'
previous_sources = {s['url']: s['sha256'] for s in json.loads(manifest_path.read_text())['sources']} if manifest_path.exists() else {}
sources, assets, faces = [], [], []
def sha(data):
    return hashlib.sha256(data).hexdigest()
def source(repo, revision, path):
    url = f'https://raw.githubusercontent.com/{repo}/{revision}/{path}'
    dest = cache / Path(path).name
    if not dest.exists():
        dest.write_bytes(urllib.request.urlopen(url).read())
    data = dest.read_bytes()
    if url in previous_sources:
        assert sha(data) == previous_sources[url], f'Pinned source checksum mismatch: {url}'
    sources.append(dict(url=url, sha256=sha(data), bytes=len(data)))
    return data

def deliver(path, data, **extra):
    dest = ROOT / path
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_bytes(data)
    assets.append(dict(path=path, sha256=sha(data), bytes=len(data), **extra))

def ranges(points):
    groups = []
    for cp in sorted(points):
        if groups and cp == groups[-1][-1] + 1:
            groups[-1].append(cp)
        else:
            groups.append([cp])
    return ','.join(f'U+{g[0]:X}' + (f'-{g[-1]:X}' if len(g) > 1 else '') for g in groups)

index = source('excalidraw/excalidraw', EXCAL, 'packages/excalidraw/fonts/Excalifont/index.ts').decode()
deliver('docs/fonts/Excalifont.upstream.ts.txt', index.encode())
# Exact copyright metadata plus complete license, with LF as the only normalization.
metadata = index.split('Origin File Name Table:\n')[1].split('\nlicenseURL:')[0]
license_text = metadata.replace('\r\n', '\n') + '\n'
deliver('public/fonts/excalifont/OFL.txt', license_text.encode())
imports = dict(re.findall(r'import (_\d) from "\./([^"]+)";', index))
for ident, mapping in re.findall(r'uri: (_\d),\s*descriptors: \{\s*unicodeRange:\s*"([^"]+)"', index):
    name = imports[ident]
    data = source('excalidraw/excalidraw', EXCAL, 'packages/excalidraw/fonts/Excalifont/' + name)
    path = 'public/fonts/excalifont/' + name
    deliver(path, data)
    faces.append(dict(family='Excalifont', cssFamily='Agamajung Excalifont', url='/' + path.removeprefix('public/'), unicodeRange=mapping))
assert len(faces) == 7
license_data = source('google/fonts', GOOGLE, 'ofl/gaegu/OFL.txt')
deliver('public/fonts/gaegu/OFL.txt', license_data)
source('google/fonts', GOOGLE, 'ofl/gaegu/Gaegu-Regular.ttf')
original = TTFont(cache / 'Gaegu-Regular.ttf')
allowed = set(range(0xAC00, 0xD7A4)) | set(range(0x3131, 0x318F))
coverage = allowed & original.getBestCmap().keys()
logo = {0xAC00, 0xB9C8, 0xC544, 0xC911}
assert logo <= coverage
remaining = sorted(coverage - logo)
groups = [('logo', sorted(logo))] + [(f'{i//256:02d}', remaining[i:i+256]) for i in range(0, len(remaining), 256)]
for label, points in groups:
    font = TTFont(cache / 'Gaegu-Regular.ttf', recalcTimestamp=False)
    options = subset.Options()
    options.flavor = 'woff2'
    options.recalc_timestamp = False
    options.canonical_order = True
    options.name_IDs = ['*']
    options.name_legacy = True
    options.name_languages = ['*']
    sub = subset.Subsetter(options=options)
    sub.populate(unicodes=points)
    sub.subset(font)
    font.flavor = 'woff2'
    path = f'public/fonts/gaegu/gaegu-regular-{label}.woff2'
    dest = ROOT / path
    font.save(dest)
    actual = set(TTFont(dest).getBestCmap())
    assert actual == set(points), (label, actual ^ set(points))
    deliver(path, dest.read_bytes(), codepoints=points)
    faces.append(dict(family='Gaegu', cssFamily='Agamajung Gaegu', url='/' + path.removeprefix('public/'), unicodeRange=ranges(points)))
css = ['/* Generated by scripts/vendor-display-fonts.py; see docs/fonts/manifest.json. */']
# Namespaced families keep installed Excalifont/Gaegu fonts from being matched when a
# vendored face fails; fallback must be the sans stack, not an untracked local display font.
for face in faces:
    css.append(f'''@font-face {{
  font-family: "{face['cssFamily']}";
  src: url("{face['url']}") format("woff2");
  font-style: normal;
  font-weight: 400;
  font-display: swap;
  unicode-range: {face['unicodeRange']};
}}''')
# Widths were measured in Chromium before assigning these local-only aliases.
metrics = json.loads((ROOT / 'docs/fonts/fallback-metrics.json').read_text())
for family, local_name, adjust, ascent, descent, unicode_range in [
    ('Display Latin Fallback', metrics['latinSource'], metrics['latinSizeAdjust'], 88.6, 37.4, 'U+0-2FFF'),
    ('Display Hangul Fallback', metrics['hangulSource'], metrics['hangulSizeAdjust'], 76, 24, 'U+3131-318E,U+AC00-D7A3'),
]:
    css.append(f'''/* Measured local sans fallback; no installed display-font shortcut. */
@font-face {{
  font-family: "{family}";
  src: local("{local_name}");
  font-style: normal;
  font-weight: 400;
  font-display: swap;
  size-adjust: {adjust:.6f}%;
  ascent-override: {ascent / (adjust / 100):.6f}%;
  descent-override: {descent / (adjust / 100):.6f}%;
  line-gap-override: 0%;
  unicode-range: {unicode_range};
}}''')
# Exact symbol advances stabilize mixed Hangul/Latin phrases and their spaces.
for symbol in metrics['symbols']:
    adjust = symbol['sizeAdjust']
    css.append(f'''@font-face {{
  font-family: "Display Latin Fallback";
  src: local("{metrics['latinSource']}");
  font-style: normal;
  font-weight: 400;
  font-display: swap;
  size-adjust: {adjust:.6f}%;
  ascent-override: {88.6 / (adjust / 100):.6f}%;
  descent-override: {37.4 / (adjust / 100):.6f}%;
  line-gap-override: 0%;
  unicode-range: U+{symbol['codepoint']:X};
}}''')
(ROOT / 'app/fonts.css').write_text('\n'.join(css) + '\n')
manifest = dict(revisions=dict(excalidraw=EXCAL, googleFonts=GOOGLE), tools=dict(fonttools=fontTools.__version__, brotli=brotli.__version__), sources=sources, assets=assets, faces=faces, gaeguCoverage=sorted(coverage), gaeguSourceGaps=sorted(allowed - coverage), totalFontBytes=sum(a['bytes'] for a in assets if a['path'].endswith('.woff2')), licenseExtraction='Excalifont: exact Origin File Name Table copyright/metadata through OTHER DEALINGS IN THE FONT SOFTWARE.; LF normalization only. Gaegu: unchanged upstream OFL.txt.')
formatted = json.dumps(manifest, indent=2, ensure_ascii=False)
# Keep complete coverage inspectable without thousands of one-integer lines.
formatted = re.sub(r'\[\s*\d[\d\s,]*\]', lambda match: '[\n' + ',\n'.join(
    '    ' + ', '.join(str(cp) for cp in json.loads(match[0])[i:i+32])
    for i in range(0, len(json.loads(match[0])), 32)
) + '\n  ]', formatted)
(ROOT / 'docs/fonts/manifest.json').write_text(formatted + '\n')
print(f'{len(faces)} faces; {len(coverage)} Gaegu code points; {len(allowed-coverage)} source gaps; {manifest["totalFontBytes"]} font bytes')
print('CSS families:', ', '.join(sorted({face['cssFamily'] for face in faces})))
for cp in [0xAC00,0x3131,0xC544]:
    glyph = original.getBestCmap().get(cp)
    print(hex(cp), glyph, original['hmtx'][glyph] if glyph else None, original['head'].unitsPerEm)
